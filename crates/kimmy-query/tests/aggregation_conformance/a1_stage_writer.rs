//! A1, A2 and A3: one writer for the paths of `$addFields`, `$set` and `$project` (q7s4g 1 to 99,
//! 682 to 685; q7s4a 12, 34, 35, 37, 47, 48, 50; q7s4d 35).
//!
//! A document without an operator is its dotted spelling and merges into the sub-document there;
//! every segment is a field name, a digit run included; a write goes into every element of an
//! array, a scalar element or parent becomes a new document, and `[]` stays `[]`. A pipeline
//! update stores exactly what the stage answers.

use super::common::{json, run};
use bson::{Bson, Document, doc};
use kimmy_query::update_pipeline::UpdatePipeline;

/// A recorded case: its line in `q7s4g.jsonl`, its stages and the documents the reference ended
/// with, in `_id` order.
type Row = (u32, Vec<Document>, Vec<Document>);

fn documents(text: &str) -> Vec<Document> {
    json(text).as_array().unwrap().iter().map(|d| d.as_document().unwrap().clone()).collect()
}

fn stages(text: &str) -> Vec<Document> {
    documents(text)
}

#[test]
fn every_recorded_stage_over_the_nine_documents_answers_as_the_reference_does() {
    // `$addFields`/`$set` of a nested document, a dotted key, both together, `$$REMOVE`, literals,
    // arrays and three levels (g:1 to 30), and `$project` with a computed leaf or an exclusion
    // (g:33, 34, 37, 39).
    let mut failures = Vec::new();
    for (line, pipeline, want) in aggregate9() {
        match run(&pipeline, set9()) {
            Ok(out) if out == want => {}
            Ok(out) => {
                failures.push(format!("q7s4g:{line}\n   ours     {out:?}\n   recorded {want:?}"))
            }
            Err(e) => failures.push(format!("q7s4g:{line}: {e}")),
        }
    }
    assert!(failures.is_empty(), "{} rows differ:\n{}", failures.len(), failures.join("\n"));
}

#[test]
fn every_recorded_stage_over_the_eight_documents_writes_digits_as_field_names() {
    // g:61 to 84 (`$addFields` and `$set` of `arr.0`, `arr.0.x`, `o.0`, `arr.1`, `arr.x`,
    // `arr.0.0`, `o.0.q`, `arr.5`, `o.1`, `arr.p` and of `$$REMOVE` there) and the `$project` flags
    // of g:97 to 99, which already read field names.
    let mut failures = Vec::new();
    for (line, pipeline, want) in aggregate8() {
        match run(&pipeline, set8()) {
            Ok(out) if out == want => {}
            Ok(out) => {
                failures.push(format!("q7s4g:{line}\n   ours     {out:?}\n   recorded {want:?}"))
            }
            Err(e) => failures.push(format!("q7s4g:{line}: {e}")),
        }
    }
    assert!(failures.is_empty(), "{} rows differ:\n{}", failures.len(), failures.join("\n"));
}

#[test]
fn a_pipeline_update_stores_exactly_what_the_stage_answers() {
    // g:40 to 56 over the nine documents, g:85 to 96 over the eight (the same stages as g:16 to
    // 30 and g:61 to 72; the reference stores what they answer).
    let mut failures = Vec::new();
    for (rows, input) in [(update9(), set9()), (update8(), set8())] {
        for (line, pipeline, want) in rows {
            let stored = (|| -> Result<Vec<Document>, String> {
                let stages: Vec<Bson> = pipeline.into_iter().map(Bson::Document).collect();
                let update = UpdatePipeline::parse(&stages).map_err(|e| e.to_string())?;
                let mut stored = input.clone();
                for doc in &mut stored {
                    update.apply(doc).map_err(|e| e.to_string())?;
                }
                Ok(stored)
            })();
            match stored {
                Ok(stored) if stored == want => {}
                Ok(stored) => failures
                    .push(format!("q7s4g:{line}\n   ours     {stored:?}\n   recorded {want:?}")),
                Err(e) => failures.push(format!("q7s4g:{line}: {e}")),
            }
        }
    }
    assert!(failures.is_empty(), "{} rows differ:\n{}", failures.len(), failures.join("\n"));
}

#[test]
fn an_empty_document_as_a_value_is_refused() {
    // g:3, 18, 42 (40180 in `$addFields`/`$set`) and g:38, 57 (51270 in `$project`).
    for stage in ["$addFields", "$set"] {
        let err = run(&[doc! { stage: { "o": {} } }], set9()).unwrap_err();
        assert!(err.contains("empty object is not a valid value"), "{stage}: {err}");
    }
    let err = run(&[doc! { "$project": { "o": {} } }], set9()).unwrap_err();
    assert!(err.contains("empty sub-projection"), "{err}");
    for stage in [doc! { "$set": { "o": {} } }, doc! { "$project": { "o": {} } }] {
        assert!(UpdatePipeline::parse(&[Bson::Document(stage)]).is_err());
    }
}

#[test]
fn a_path_that_is_the_prefix_of_another_is_still_refused() {
    // d:35: `{a: 1, "a.b": 2}` is 40176, in a nested spelling too.
    for spec in [doc! { "a": 1, "a.b": 2 }, doc! { "a": { "b": 1 }, "a.b.c": 2 }] {
        let err = run(&[doc! { "$set": spec.clone() }], vec![doc! { "_id": 1 }]).unwrap_err();
        assert!(err.contains("conflicting paths"), "{spec}: {err}");
    }
}

