//! An `$all` inside a value-form `$elemMatch` is asked of each member as one whole value:
//! `{a: {$elemMatch: {$all: [1]}}}` selects a document with a member **equal to** 1, and not one
//! whose member is an array holding a 1 (q7s3l0001, 0002: over `[[1, 2], [3, 4]]` nothing, over
//! `[1, [2]]` and `[1, 2]` yes). `{$all: [[1, 2]]}` selects a member equal to the array `[1, 2]`
//! (q7s3f0323, q7s3l0017, 0018), `{$all: [1, 2]}` and `{$all: []}` select nothing (q7s3f0322,
//! q7s3l0007, 0008, 0011, 0012), an `$all` beside `$gt`, `$lt` or `$ne` is ANDed with it on the
//! same member in either listing order (0003 to 0006, 0013 to 0016), and with `$size` or an inner
//! `$elemMatch` beside it nothing matches (0009, 0010, 0019, 0020).
//!
//! The 22 cases of `cases.rs` are generated by `data/elem_match_all_gen.py` from the recordings;
//! q7s3l0011 and q7s3l0012 (`$all: []` inside the `$elemMatch`: nothing) are answered since an
//! empty `$all` matches no document, on an array element as on a field.
//! All of them are finds: no `$pull` of these bodies is recorded, so what a `$pull` does with an
//! `$all` in an `$elemMatch` is UNRECORDED and is not asserted here.

mod cases;

use bson::Document;
use kimmy_query::filter;

fn answered(filter_doc: &Document, docs: &[Document]) -> Vec<i32> {
    let parsed = filter::parse(filter_doc).expect("a filter that parses");
    docs.iter()
        .filter(|d| filter::matches(&parsed, d).expect("a filter that evaluates"))
        .map(|d| d.get_i32("_id").expect("an Int32 _id"))
        .collect()
}

#[test]
fn every_recorded_all_in_an_elem_match_answers_as_recorded() {
    let all = cases::cases();
    assert_eq!(all.len(), 22, "premise: q7s3f 322, 323 and the 20 cases of q7s3l");
    let mut wrong = Vec::new();
    for case in &all {
        let got = answered(&case.filter, &(case.docs)());
        if got != case.ids {
            wrong.push(format!(
                "{} (line {}): {}: recorded {:?}, ours {:?}",
                case.label, case.line, case.filter, case.ids, got
            ));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} cases differ:\n{}",
        wrong.len(),
        all.len(),
        wrong.join("\n")
    );
}
