#!/usr/bin/env python3
"""Rebuild elem_match_all/cases.rs from the reference recordings.

    python3 data/elem_match_all_gen.py <reference-6.0.5 directory> > elem_match_all/cases.rs
    rustfmt --edition 2024 elem_match_all/cases.rs

Reads q7s3f line 322 and 323 and every case of q7s3l (20 finds): an `$all` inside a value-form
`$elemMatch`, asked of each member as one whole value. One `Case` per recorded find: the label, the
line of the set's `.jsonl`, the documents it ran over (`beforeOrdered`), the filter
(`commandOrdered`) and the ids the reference answered. The recordings are typed.
"""
import hashlib
import json
import sys

WRAPPERS = {"$oid", "$date", "$binary", "$regularExpression", "$timestamp", "$numberDecimal", "$minKey", "$maxKey", "$code", "$symbol", "$undefined", "$dbPointer"}
# Cases left out of the table: none. (The two cases with an empty `$all` inside an `$elemMatch`,
# q7s3l0011 and q7s3l0012, were left out until this commit, which lifts the refusal of an empty
# `$all` on an array element.)
LEFT_OUT = set()
LISTED = {"q7s3f": {322, 323}, "q7s3l": set(range(1, 21))}


def flat(v):
    if isinstance(v, dict):
        if list(v) == ["$ordered"]:
            return {k: flat(x) for k, x in v["$ordered"]}
        return {k: flat(x) for k, x in v.items()}
    if isinstance(v, list):
        return [flat(x) for x in v]
    return v


def rs(v):
    if v is None:
        return "Bson::Null"
    if v is True or v is False:
        return "Bson::Boolean(%s)" % str(v).lower()
    if isinstance(v, str):
        return "Bson::String(%s.to_string())" % json.dumps(v)
    if isinstance(v, list):
        return "Bson::Array(vec![%s])" % ", ".join(rs(x) for x in v)
    if isinstance(v, dict):
        if "$numberInt" in v:
            return "Bson::Int32(%s)" % v["$numberInt"]
        if "$numberLong" in v:
            return "Bson::Int64(%s)" % v["$numberLong"]
        if "$numberDouble" in v:
            d = v["$numberDouble"]
            if d in ("NaN", "Infinity", "-Infinity"):
                raise SystemExit("unsupported double " + d)
            return "Bson::Double(%s)" % (d if ("." in d or "e" in d.lower()) else d + ".0")
        if any(k in WRAPPERS for k in v):
            raise SystemExit("unsupported " + json.dumps(v))
        return "Bson::Document(%s)" % doc(v)
    raise SystemExit("unsupported " + repr(v))


def doc(d):
    if not d:
        return "Document::new()"
    return "doc! { %s }" % ", ".join("%s: %s" % (json.dumps(k), rs(x)) for k, x in d.items())


base = sys.argv[1].rstrip("/") + "/"
docsets, cases = {}, []
for name, wanted in LISTED.items():
    for n, line in enumerate(open(base + name + ".jsonl"), 1):
        if n not in wanted:
            continue
        r = json.loads(line)
        if r["label"].split()[0] in LEFT_OUT:
            continue
        before = flat(r["beforeOrdered"])
        h = hashlib.md5(json.dumps(before).encode()).hexdigest()[:8]
        docsets.setdefault(h, before)
        filt = flat(r["commandOrdered"])["filter"]
        ids = [int(x["$numberInt"]) for x in r["reply"]["ids"]]
        cases.append((r["label"].split()[0], n, h, filt, ids))

print("""//! Generated by `tests/data/elem_match_all_gen.py` from the recordings q7s3f (322, 323) and q7s3l
//! (reference 6.0.5). Do not edit.

use bson::{Bson, Document, doc};

pub struct Case {
    pub label: &'static str,
    pub line: u32,
    pub docs: fn() -> Vec<Document>,
    pub filter: Document,
    pub ids: Vec<i32>,
}
""")
for h, before in docsets.items():
    print("fn docs_%s() -> Vec<Document> {\n    vec![\n%s\n    ]\n}\n" % (h, "\n".join("        %s," % doc(d) for d in before)))
print("pub fn cases() -> Vec<Case> {\n    vec![")
for label, line, h, filt, ids in cases:
    print("        Case {\n            label: \"%s\",\n            line: %d,\n            docs: docs_%s,\n            filter: %s,\n            ids: vec![%s],\n        }," % (label, line, h, doc(filt), ", ".join(map(str, ids))))
print("    ]\n}")
