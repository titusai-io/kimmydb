#!/usr/bin/env python3
"""Rebuild query_conformance/resolver_bound_cases.rs from the reference recordings q7s3m and q7s4o.

    python3 data/resolver_bound_cases_gen.py <reference-6.0.5 directory> > query_conformance/resolver_bound_cases.rs
    rustfmt --edition 2024 query_conformance/resolver_bound_cases.rs

`cases_bounds()`: q7s3m 1 to 22, a `find` of the 16 documents of q7s3f0035 sorted by two keys
through one array (`{"a.c": 1, "a.d": 1, _id: 1}` and its descending twin), each with a `skip` and a
`limit` (a `limit` of 0 or none is no limit). The answer is `reply.ids`.

`cases_whole()`: q7s3m 23 to 54, q7s4o 1 to 20 and q7s4p 1 to 16, as `Rec`s: an update (`$push` with `$sort`; the
answer is `afterOrdered`, the collection after), an aggregate (`$sortArray`, `$sort`; the answer is
`reply.docs`) and a find (the answer is `reply.ids`). The documents of every case are `beforeOrdered`.
No case reads `before` or the input `y` as an answer.
"""
import hashlib
import json
import sys

WRAPPERS = {"$oid", "$date", "$binary", "$regularExpression", "$timestamp", "$minKey", "$maxKey", "$code", "$symbol", "$undefined", "$dbPointer"}


def flat(v):
    if isinstance(v, dict):
        if list(v) == ["$ordered"]:
            return {k: flat(x) for k, x in v["$ordered"]}
        return {k: flat(x) for k, x in v.items()}
    if isinstance(v, list):
        return [flat(x) for x in v]
    return v


def rs(v):
    if v is None:
        return "Bson::Null"
    if v is True or v is False:
        return "Bson::Boolean(%s)" % str(v).lower()
    if isinstance(v, str):
        return "Bson::String(%s.to_string())" % json.dumps(v)
    if isinstance(v, list):
        return "Bson::Array(vec![%s])" % ", ".join(rs(x) for x in v)
    if isinstance(v, dict):
        if "$numberInt" in v:
            return "Bson::Int32(%s)" % v["$numberInt"]
        if "$numberLong" in v:
            return "Bson::Int64(%s)" % v["$numberLong"]
        if "$numberDouble" in v:
            d = v["$numberDouble"]
            return "Bson::Double(%s)" % (d if ("." in d or "e" in d.lower()) else d + ".0")
        if "$numberDecimal" in v:
            return "dec(%s)" % json.dumps(v["$numberDecimal"])
        if any(k in WRAPPERS for k in v):
            raise SystemExit("unsupported " + json.dumps(v))
        return "Bson::Document(%s)" % doc(v)
    raise SystemExit("unsupported " + repr(v))


def doc(d):
    if not d:
        return "Document::new()"
    return "doc! { %s }" % ", ".join("%s: %s" % (json.dumps(k), rs(x)) for k, x in d.items())


def count(v):
    return int(v["$numberInt"]) if isinstance(v, dict) else int(v)


base = sys.argv[1].rstrip("/") + "/"


def labels(name):
    out = {}
    for n, text in enumerate(open(base + name + ".out"), 1):
        if text.startswith("--- " + name):
            out[text.split()[1]] = n
    return out


docsets, bounds, whole = {}, [], []
for name, wanted_bounds, wanted_whole in (("q7s3m", range(1, 23), range(23, 55)), ("q7s4o", range(0), range(1, 21)), ("q7s4p", range(0), range(1, 17))):
    lines = labels(name)
    for n, line in enumerate(open(base + name + ".jsonl"), 1):
        if n not in wanted_bounds and n not in wanted_whole:
            continue
        r = json.loads(line)
        before = flat(r["beforeOrdered"])
        h = hashlib.md5(json.dumps(before).encode()).hexdigest()[:8]
        docsets.setdefault(h, before)
        c = flat(r["commandOrdered"])
        label = r["label"].split()[0]
        if n in wanted_bounds:
            ids = [int(x["$numberInt"]) for x in r["reply"]["ids"]]
            bounds.append((label, lines[label], h, c["sort"], count(c.get("skip", 0)), count(c.get("limit", 0)), ids))
            continue
        kind = r["kind"]
        if kind == "find":
            run = "Run::Find { filter: %s, sort: %s }" % (doc(c.get("filter", {})), doc(c["sort"]))
            out = "Outcome::Ids(vec![%s])" % ", ".join(str(int(x["$numberInt"])) for x in r["reply"]["ids"])
        elif kind == "aggregate":
            run = "Run::Pipeline(vec![%s])" % ", ".join(doc(st) for st in c["pipeline"])
            out = "Outcome::Docs(vec![%s])" % ", ".join(doc(d) for d in flat(r["reply"]["docsOrdered"] if "docsOrdered" in r["reply"] else r["reply"]["docs"]))
        else:
            run = "Run::Update { query: %s, update: %s }" % (doc(c["q"]), doc(c["u"]))
            out = "Outcome::Docs(vec![%s])" % ", ".join(doc(d) for d in flat(r["afterOrdered"]))
        whole.append((label, lines[label], h, run, out))

print("""//! Generated by `tests/data/resolver_bound_cases_gen.py` from the recordings q7s3m, q7s4o and q7s4p (reference
//! 6.0.5). Do not edit.

use super::common::dec;
use super::resolver_sorts::{Bound, Outcome, Rec, Run};
use bson::{Bson, Document, doc};
""")
for h, before in docsets.items():
    print("fn docs_%s() -> Vec<Document> {\n    vec![\n%s\n    ]\n}\n" % (h, "\n".join("        %s," % doc(d) for d in before)))
print("pub fn cases_bounds() -> Vec<Bound> {\n    vec![")
for label, line, h, sort, skip, limit, ids in bounds:
    print("        Bound {\n            label: \"%s\",\n            line: %d,\n            docs: docs_%s,\n            sort: %s,\n            skip: %d,\n            limit: %d,\n            ids: vec![%s],\n        }," % (label, line, h, doc(sort), skip, limit, ", ".join(map(str, ids))))
print("    ]\n}\n")
print("pub fn cases_whole() -> Vec<Rec> {\n    vec![")
for label, line, h, run, out in whole:
    print("        Rec {\n            label: \"%s\",\n            line: %d,\n            docs: docs_%s,\n            run: %s,\n            outcome: %s,\n        }," % (label, line, h, run, out))
print("    ]\n}")
