#!/usr/bin/env python3
"""The table of decimal sums `decimal_sum_table.tsv`, for `decimal_exact_inc.rs`.

Command line (from crates/kimmy-core/tests/data):   python3 -I gen_decimal_sums.py > decimal_sum_table.tsv

Each row is `a<TAB>b<TAB>ok`: two Decimal128 spellings (a coefficient of up to 34 digits, often padded with
trailing zeros, at an exponent, both signs, exponents up to 6,000 apart) and whether their EXACT sum is a
Decimal128 at some exponent (a coefficient of at most 34 digits once the trailing zeros are dropped, an exponent
in -6176..6111), `1` or `0`. The sums are computed by Python's `decimal` at a precision of 13,000 digits, which
holds every sum here exactly (the operands' digits span at most 6,100 + 34 positions): an arithmetic that shares
no code with the Rust one. The seed is fixed: the file is a function of this script.
"""
import random
import sys
from decimal import Decimal, Context

CTX = Context(prec=13000, Emax=100000, Emin=-100000)
MIN_EXP, MAX_EXP = -6176, 6111


def representable(s):
    if s == 0:
        return True
    t = s.normalize(CTX)
    sign, digits, exp = t.as_tuple()
    return len(digits) <= 34 and MIN_EXP <= exp <= MAX_EXP


def spell(sign, coef, exp):
    return "%s%dE%+d" % ("-" if sign else "", coef, exp)


def operand(rnd, exp_lo=-60, exp_hi=6100):
    digits = rnd.randint(1, 34)
    coef = rnd.randint(10 ** (digits - 1), 10 ** digits - 1)
    # pad: trailing zeros while the coefficient stays within 34 digits
    pad = rnd.choice([0, 0, 1, 3, 6, 10, 20, 33])
    pad = min(pad, 34 - digits)
    coef *= 10 ** pad
    return rnd.random() < 0.5, coef, rnd.randint(exp_lo, exp_hi)


def row(rnd):
    sa, ca, ea = operand(rnd)
    gap = rnd.choice([0, 1, 2, 3, 5, 6, 10, 33, 34, 35, 40, 100, 1000, 6000])
    sb, cb, eb = operand(rnd, -60, 6100)
    eb = ea + gap * rnd.choice([-1, 1])
    eb = max(-6176, min(6111, eb))
    # half the rows are built to cancel or to carry to a round number
    mode = rnd.random()
    if mode < 0.25:
        sb, cb = (not sa), ca          # a - a at another exponent shape: a + (-a), then a small tail below
    elif mode < 0.4:
        cb = 10 ** rnd.randint(0, 33)  # a power of ten: the sum may be a round number
    a = Decimal(("-" if sa else "") + "%dE%+d" % (ca, ea))
    b = Decimal(("-" if sb else "") + "%dE%+d" % (cb, eb))
    return spell(sa, ca, ea), spell(sb, cb, eb), representable(CTX.add(a, b))


def main():
    rnd = random.Random(20261115)
    want = {True: 2600, False: 2600}
    have = {True: 0, False: 0}
    rows = []
    while have[True] < want[True] or have[False] < want[False]:
        a, b, ok = row(rnd)
        if have[ok] < want[ok]:
            have[ok] += 1
            rows.append((a, b, ok))
    rnd.shuffle(rows)
    # the named cases of the review's finding: 1E+39 + 1000000 and 1E+39 - 1000000
    rows[:0] = [("1E+39", "1000000E+0", True), ("1E+39", "-1000000E+0", True)]
    print("# generated by gen_decimal_sums.py: a, b, whether a + b is exactly a Decimal128 (1) or not (0)")
    for a, b, ok in rows:
        print("%s\t%s\t%d" % (a, b, int(ok)))


if __name__ == "__main__":
    main()
